"""
app/services/research/qdrant_service.py

Local Qdrant storage for Research Brain embeddings.

Qdrant runs in embedded file mode via QdrantClient(path=".qdrant"). This keeps
Phase 2 local and lightweight: no Docker, no external vector server, no
LangChain/LlamaIndex wrappers, and no retrieval/search endpoint yet.
"""

import logging
import asyncio
import threading
import uuid
from collections.abc import Mapping, Sequence
from functools import lru_cache
from pathlib import Path
from typing import Any

from qdrant_client import QdrantClient, models

logger = logging.getLogger(__name__)

QDRANT_PATH = Path(".qdrant")
COLLECTION_NAME = "research_papers"
EMBEDDING_MODEL_NAME = "BAAI/bge-small-en-v1.5"
VECTOR_SIZE = 384

_QDRANT_LOCK = threading.RLock()


class QdrantServiceError(Exception):
    """Raised when local Qdrant storage operations fail."""


@lru_cache(maxsize=1)
def get_qdrant_client() -> QdrantClient:
    """Return a singleton local Qdrant client backed by the .qdrant directory."""
    QDRANT_PATH.mkdir(parents=True, exist_ok=True)
    return QdrantClient(path=str(QDRANT_PATH))


def ensure_research_collection() -> None:
    """Create the research_papers collection if it does not already exist."""
    with _QDRANT_LOCK:
        client = get_qdrant_client()
        try:
            if client.collection_exists(COLLECTION_NAME):
                return

            client.create_collection(
                collection_name=COLLECTION_NAME,
                vectors_config=models.VectorParams(
                    size=VECTOR_SIZE,
                    distance=models.Distance.COSINE,
                ),
            )
            logger.info(
                "Created Qdrant collection %s at %s with vector_size=%d.",
                COLLECTION_NAME,
                QDRANT_PATH,
                VECTOR_SIZE,
            )
        except Exception as exc:
            logger.exception("Failed to initialize Qdrant collection: %s", exc)
            raise QdrantServiceError("Failed to initialize local Qdrant collection.") from exc


def delete_paper_vectors(paper_id: uuid.UUID) -> None:
    """Delete existing vectors for one paper so embedding generation is idempotent."""
    with _QDRANT_LOCK:
        ensure_research_collection()
        client = get_qdrant_client()
        try:
            client.delete(
                collection_name=COLLECTION_NAME,
                points_selector=models.Filter(
                    must=[
                        models.FieldCondition(
                            key="paper_id",
                            match=models.MatchValue(value=str(paper_id)),
                        )
                    ]
                ),
                wait=True,
            )
        except Exception as exc:
            logger.exception("Failed to delete existing vectors for paper_id=%s: %s", paper_id, exc)
            raise QdrantServiceError(f"Failed to delete existing vectors for paper {paper_id}.") from exc


def upsert_paper_chunks(
    vectors: Sequence[Sequence[float]],
    payloads: Sequence[Mapping[str, Any]],
) -> int:
    """
    Insert embedded paper chunks into local Qdrant.

    Args:
        vectors: Embedding vectors generated by the local model.
        payloads: Metadata for each vector. Each payload should include
            paper_id, chunk_index, and text_content.

    Returns:
        Number of vectors stored.
    """
    if len(vectors) != len(payloads):
        raise ValueError("vectors and payloads must have the same length.")
    if not vectors:
        return 0

    with _QDRANT_LOCK:
        ensure_research_collection()
        client = get_qdrant_client()

        points = [
            models.PointStruct(
                id=str(uuid.uuid4()),
                vector=_normalize_vector(vector),
                payload=dict(payload),
            )
            for vector, payload in zip(vectors, payloads, strict=True)
        ]

        try:
            client.upsert(
                collection_name=COLLECTION_NAME,
                points=points,
                wait=True,
            )
        except Exception as exc:
            logger.exception("Failed to upsert %d vectors into Qdrant: %s", len(points), exc)
            raise QdrantServiceError("Failed to upsert paper chunk vectors.") from exc

    logger.info("Stored %d vectors in Qdrant collection %s.", len(points), COLLECTION_NAME)
    return len(points)


async def search_chunks(
    query_vector: list[float],
    paper_id: uuid.UUID | None = None,
    limit: int = 5,
) -> list[dict[str, Any]]:
    """
    Search embedded paper chunks by cosine similarity.

    Args:
        query_vector: 384-dimensional query embedding.
        paper_id: Optional paper scope. When provided, only chunks from this
            paper are searched.
        limit: Maximum number of scored chunks to return.

    Returns:
        List of dictionaries containing payload fields and Qdrant similarity score.
    """
    if limit <= 0:
        raise ValueError("limit must be greater than 0.")

    return await asyncio.to_thread(_search_chunks_sync, query_vector, paper_id, limit)


def _normalize_vector(vector: Sequence[float]) -> list[float]:
    """Validate vector dimensionality and convert values to plain floats."""
    if len(vector) != VECTOR_SIZE:
        raise ValueError(f"Expected vector size {VECTOR_SIZE}, received {len(vector)}.")
    return [float(value) for value in vector]


def _search_chunks_sync(
    query_vector: Sequence[float],
    paper_id: uuid.UUID | None,
    limit: int,
) -> list[dict[str, Any]]:
    """Run a blocking local Qdrant vector query."""
    normalized_query = _normalize_vector(query_vector)
    query_filter = _build_paper_filter(paper_id)

    with _QDRANT_LOCK:
        ensure_research_collection()
        client = get_qdrant_client()
        try:
            response = client.query_points(
                collection_name=COLLECTION_NAME,
                query=normalized_query,
                query_filter=query_filter,
                limit=limit,
                with_payload=True,
                with_vectors=False,
            )
        except Exception as exc:
            logger.exception("Qdrant vector search failed: %s", exc)
            raise QdrantServiceError("Failed to search local Qdrant collection.") from exc

    results: list[dict[str, Any]] = []
    for point in response.points:
        payload = dict(point.payload or {})
        results.append(
            {
                "point_id": str(point.id),
                "score": float(point.score),
                "paper_id": payload.get("paper_id"),
                "chunk_id": payload.get("chunk_id"),
                "chunk_index": payload.get("chunk_index"),
                "text_content": payload.get("text_content", ""),
            }
        )

    return results


def _build_paper_filter(paper_id: uuid.UUID | None) -> models.Filter | None:
    """Build an optional Qdrant payload filter for one paper."""
    if paper_id is None:
        return None

    return models.Filter(
        must=[
            models.FieldCondition(
                key="paper_id",
                match=models.MatchValue(value=str(paper_id)),
            )
        ]
    )
