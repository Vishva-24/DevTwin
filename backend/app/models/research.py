"""
app/models/research.py

SQLAlchemy ORM models for Phase 2: Research Intelligence Engine.

Design notes:
  - Paper stores the deterministic output of PDF ingestion and parsing.
  - PaperChunk is prepared for later chunk persistence without adding
    embeddings, vector columns, chat state, or graph-specific concerns.
  - authors uses JSONB so the parser can preserve either simple author names
    or richer author metadata later without a schema rewrite.
  - raw_markdown stores the pymupdf4llm markdown output separately from future
    AI-generated research objects.
  - research_manifest stores the structured Gemini-generated Knowledge Object
    separately from deterministic parser output and raw markdown.
"""

import uuid
from datetime import datetime, timezone

from sqlalchemy import DateTime, ForeignKey, Integer, String, Text, UniqueConstraint, text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.sql import func

from app.core.database import Base


def _utcnow() -> datetime:
    """Return the current UTC datetime as a timezone-aware value."""
    return datetime.now(timezone.utc)


class Paper(Base):
    """
    Represents a parsed academic paper or PDF uploaded into DevTwin.

    This table is intentionally ingestion-focused: it stores file identity,
    extracted metadata, page count, and raw markdown. Higher-level summaries,
    manifests, graph nodes, embeddings, and agent memory are later phases.
    """

    __tablename__ = "papers"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        comment="Surrogate primary key generated by the application.",
    )
    title: Mapped[str | None] = mapped_column(
        String(1024),
        nullable=True,
        index=True,
        comment="Best-effort title extracted deterministically from the PDF.",
    )
    file_name: Mapped[str] = mapped_column(
        String(512),
        nullable=False,
        comment="Original uploaded PDF file name.",
    )
    file_path: Mapped[str] = mapped_column(
        String(2048),
        nullable=False,
        comment="Server-side path where the uploaded PDF was stored for parsing.",
    )
    authors: Mapped[list[str]] = mapped_column(
        JSONB,
        nullable=False,
        default=list,
        server_default=text("'[]'::jsonb"),
        comment="Author names or future structured author metadata extracted from the paper.",
    )
    abstract: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment="Best-effort abstract extracted deterministically from the PDF.",
    )
    total_pages: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
        comment="Total number of pages reported by the PDF parser.",
    )
    uploaded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        server_default=func.now(),
        comment="UTC timestamp when this paper was uploaded.",
    )
    raw_markdown: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment="Raw markdown emitted by pymupdf4llm during deterministic PDF parsing.",
    )
    research_manifest: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "Structured ResearchManifest JSON generated from selected paper chunks. "
            "Contains KG-oriented fields such as core_concepts, methodology_summary, "
            "key_findings, and tech_stack_mentions."
        ),
    )

    chunks: Mapped[list["PaperChunk"]] = relationship(
        "PaperChunk",
        back_populates="paper",
        cascade="all, delete-orphan",
        order_by="PaperChunk.chunk_index",
        lazy="select",
    )

    def __repr__(self) -> str:
        return f"<Paper id={str(self.id)[:8]} title={self.title!r}>"


class PaperChunk(Base):
    """
    Represents one persisted text chunk derived from a parsed paper.

    Chunking is implemented in a later step; this model establishes the storage
    contract now so downstream services can depend on stable table semantics.
    """

    __tablename__ = "paper_chunks"
    __table_args__ = (
        UniqueConstraint(
            "paper_id",
            "chunk_index",
            name="uq_paper_chunks_paper_id_chunk_index",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        comment="Surrogate primary key generated by the application.",
    )
    paper_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("papers.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="References the parsed paper this chunk belongs to.",
    )
    chunk_index: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        comment="Zero-based order of this chunk within the paper.",
    )
    content: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment="Plain markdown/text content for this chunk.",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        server_default=func.now(),
        comment="UTC timestamp when this chunk row was created.",
    )

    paper: Mapped["Paper"] = relationship(
        "Paper",
        back_populates="chunks",
        lazy="select",
    )

    def __repr__(self) -> str:
        return (
            f"<PaperChunk id={str(self.id)[:8]} "
            f"paper_id={str(self.paper_id)[:8]} "
            f"chunk_index={self.chunk_index}>"
        )
