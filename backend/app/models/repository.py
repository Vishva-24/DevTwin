"""
app/models/repository.py

SQLAlchemy ORM models for the two core tables:

  - Repository  — one row per unique GitHub URL
  - Analysis    — one row per analysis run of a repository

Design notes:
  - UUIDs are generated server-side (no dependency on DB sequences).
  - JSONB columns store raw structured output from each parser module.
    This avoids premature normalization in Phase 1 while still being
    fully queryable in PostgreSQL.
  - updated_at uses onupdate= so it is set automatically on every UPDATE.
  - AnalysisStatus is a Python Enum mapped to a DB VARCHAR — avoids
    a PostgreSQL ENUM type that requires a migration to extend.
"""

import enum
import uuid
from datetime import datetime, timezone

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship
from sqlalchemy.sql import func

from app.core.database import Base


# ─── Helpers ──────────────────────────────────────────────────────────────────


def _utcnow() -> datetime:
    """Return the current UTC datetime (timezone-aware)."""
    return datetime.now(timezone.utc)


# ─── Enums ────────────────────────────────────────────────────────────────────


class AnalysisStatus(str, enum.Enum):
    """
    Lifecycle states for an analysis run.

    Stored as VARCHAR so adding new states only requires an app deploy,
    not a PostgreSQL ALTER TYPE migration.
    """
    PENDING = "pending"      # created, waiting to be picked up
    RUNNING = "running"      # actively being processed
    COMPLETED = "completed"  # all parser + AI steps finished successfully
    FAILED = "failed"        # an unrecoverable error occurred


# ─── Repository model ─────────────────────────────────────────────────────────


class Repository(Base):
    """
    Represents a unique GitHub repository submitted for analysis.

    One Repository row can have many Analysis rows (e.g., when the repo
    is re-submitted after new commits are pushed).

    The (github_url, latest_commit_hash) pair is used as the fingerprint
    to detect whether re-analysis is necessary.
    """

    __tablename__ = "repositories"
    __table_args__ = (
        UniqueConstraint("github_url", name="uq_repositories_github_url"),
    )

    # ── Primary key ────────────────────────────────────────────────────────
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        comment="Surrogate primary key — UUID generated by the application.",
    )

    # ── GitHub identity ────────────────────────────────────────────────────
    github_url: Mapped[str] = mapped_column(
        String(512),
        nullable=False,
        index=True,
        comment="Canonical GitHub URL as submitted by the user, e.g. https://github.com/owner/repo.",
    )
    owner: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        comment="Repository owner (user or organisation) parsed from the GitHub URL.",
    )
    repo_name: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        comment="Repository name parsed from the GitHub URL.",
    )

    # ── GitHub metadata (fetched from GitHub API) ──────────────────────────
    default_branch: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        default="main",
        comment="Default branch of the repository as reported by the GitHub API.",
    )
    description: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment="Repository description from GitHub. May be null if the owner hasn't set one.",
    )
    stars: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        comment="Stargazer count at the time of the most recent fetch.",
    )
    primary_language: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        comment="Primary programming language as detected by GitHub (e.g. Python, TypeScript).",
    )
    is_private: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        comment="True if the repository is private. Requires a PAT with 'repo' scope to analyse.",
    )

    # ── Fingerprinting ─────────────────────────────────────────────────────
    latest_commit_hash: Mapped[str | None] = mapped_column(
        String(40),
        nullable=True,
        index=True,
        comment=(
            "SHA-1 hash of the HEAD commit on the default branch at the time of last fetch. "
            "Used to skip re-analysis when the repository has not changed."
        ),
    )

    # ── Timestamps ─────────────────────────────────────────────────────────
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        server_default=func.now(),
        comment="UTC timestamp when this repository record was first created.",
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        onupdate=_utcnow,
        server_default=func.now(),
        comment="UTC timestamp of the most recent update to this record.",
    )

    # ── Relationships ──────────────────────────────────────────────────────
    analyses: Mapped[list["Analysis"]] = relationship(
        "Analysis",
        back_populates="repository",
        cascade="all, delete-orphan",
        order_by="Analysis.created_at.desc()",
        lazy="select",
    )

    def __repr__(self) -> str:
        return f"<Repository id={self.id!s:.8} owner={self.owner!r} repo={self.repo_name!r}>"


# ─── Analysis model ───────────────────────────────────────────────────────────


class Analysis(Base):
    """
    Represents one analysis run of a repository.

    Each parser module writes its output into the appropriate JSONB column.
    This design keeps deterministic (parser) output strictly separate from
    AI-generated output (summary), satisfying the Phase 1 architectural rule:
    'Keep parser output separate from AI-generated output.'

    Column population schedule:
      Step 1 (this PR):   file_manifest
      Step 2 (parsers):   tech_stack, api_routes, dependency_graph
      Step 3 (Gemini):    summary_json
    """

    __tablename__ = "analyses"

    # ── Primary key ────────────────────────────────────────────────────────
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        comment="Surrogate primary key — UUID generated by the application.",
    )

    # ── Foreign key ────────────────────────────────────────────────────────
    repository_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("repositories.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="References the Repository this analysis belongs to.",
    )

    # ── Status ─────────────────────────────────────────────────────────────
    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default=AnalysisStatus.PENDING.value,
        index=True,
        comment=(
            "Lifecycle state of this analysis run. "
            "One of: pending, running, completed, failed."
        ),
    )
    error_message: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment="Human-readable error description. Only populated when status='failed'.",
    )

    # ── Fingerprint snapshot ───────────────────────────────────────────────
    commit_hash: Mapped[str | None] = mapped_column(
        String(40),
        nullable=True,
        comment=(
            "SHA-1 of the HEAD commit that was analysed. "
            "Snapshot of Repository.latest_commit_hash at the time this analysis was created."
        ),
    )

    # ── Parser outputs (JSONB) ─────────────────────────────────────────────
    file_manifest: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "Raw file tree fetched from the GitHub API. "
            "Structure: { owner, repo_name, commit_hash, total_files, files: [FileEntry] }. "
            "Populated in Step 1 (GitHub Service)."
        ),
    )
    tech_stack: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "Detected technology stack. "
            "Structure: { languages: [], frameworks: [], databases: [], package_managers: [] }. "
            "Populated in Step 2 (Tech Stack Detector)."
        ),
    )
    api_routes: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "Extracted API endpoints. "
            "Structure: { routes: [{ method, path, file, line }] }. "
            "Populated in Step 2 (Route Extractor)."
        ),
    )
    dependency_graph: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "File-level import dependency graph built with Python AST. "
            "Structure: { nodes: [{ id, path }], edges: [{ source, target }] }. "
            "Populated in Step 2 (AST Service)."
        ),
    )
    architecture_hints: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "Heuristic architecture analysis from repository paths. "
            "Structure: { primary_pattern, confidence, evidence, all_scores }. "
            "Populated in Step 2 (Architecture Service)."
        ),
    )

    # ── AI output (intentionally separate from parser outputs) ────────────
    summary: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
        comment=(
            "Legacy text summary generated by Gemini. "
            "Derived from the structured manifest — never from raw source code. "
            "Populated in Step 3 (LLM Summarizer)."
        ),
    )
    summary_json: Mapped[dict | None] = mapped_column(
        JSONB,
        nullable=True,
        comment=(
            "Structured human-readable repository summary generated by Gemini. "
            "Structure: { project_purpose, architecture_summary, key_features, "
            "strengths_and_weaknesses }. Derived from parser metadata only. "
            "Populated in Step 3 (LLM Summarizer)."
        ),
    )

    # ── Timestamps ─────────────────────────────────────────────────────────
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=_utcnow,
        server_default=func.now(),
        comment="UTC timestamp when this analysis was created.",
    )
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="UTC timestamp when this analysis reached 'completed' or 'failed' status.",
    )

    # ── Relationships ──────────────────────────────────────────────────────
    repository: Mapped["Repository"] = relationship(
        "Repository",
        back_populates="analyses",
        lazy="select",
    )

    def __repr__(self) -> str:
        return (
            f"<Analysis id={self.id!s:.8} "
            f"repo_id={self.repository_id!s:.8} "
            f"status={self.status!r}>"
        )
